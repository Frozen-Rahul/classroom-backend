export const schema = `
CREATE TABLE IF NOT EXISTS subjects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  code TEXT NOT NULL UNIQUE,
  department TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS classes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  subject_id BIGINT REFERENCES subjects(id) ON DELETE SET NULL,
  teacher_id TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  capacity INTEGER NOT NULL DEFAULT 30 CHECK (capacity > 0),
  description TEXT NOT NULL DEFAULT '',
  schedules JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(schedules) = 'array')
);

INSERT INTO subjects (name, code, department, description) VALUES
  ('Mathematics', 'MATH101', 'Mathematics', 'Core mathematics'),
  ('Computer Science', 'CS101', 'Computer Science', 'Computer science fundamentals'),
  ('Physics', 'PHY101', 'Physics', 'Physics fundamentals'),
  ('Chemistry', 'CHEM101', 'Chemistry', 'Chemistry fundamentals')
ON CONFLICT (code) DO NOTHING;

INSERT INTO classes (name, subject_id, teacher_id, status, capacity, description, schedules)
SELECT seed.name, subjects.id, seed.teacher_id, seed.status, seed.capacity, seed.description, '[]'::jsonb
FROM (VALUES
  ('Mathematics - Section A', 'MATH101', '1', 'active', 30, 'Introduction to mathematics'),
  ('Computer Science - Section A', 'CS101', '2', 'active', 28, 'Introduction to computer science'),
  ('Physics - Section A', 'PHY101', '3', 'inactive', 24, 'Introduction to physics')
) AS seed(name, subject_code, teacher_id, status, capacity, description)
JOIN subjects ON subjects.code = seed.subject_code
WHERE NOT EXISTS (SELECT 1 FROM classes WHERE classes.name = seed.name);
`;
